# 新类别 hint 用「形容词」，让关掉类别提示时仍能在 setup 标注
HINT_OVERRIDE = {"形容词": "形容词"}


def main():
    existing = json.load(open("/tmp/draw_words.json"))
    merged = OrderedDict()  # text -> record，保序、去重
    for w in existing:
        merged[w["text"]] = {"text": w["text"], "hint": w["hint"], "difficulty": w["difficulty"]}

    added, dup = 0, 0
    for hint, by_diff in NEW.items():
        for diff, words in by_diff.items():
            for text in words:
                rec = {"text": text, "hint": HINT_OVERRIDE.get(hint, hint), "difficulty": diff}
                if text in merged:
                    dup += 1
                    continue
                merged[text] = rec
                added += 1

    out = list(merged.values())
    # 校验
    for r in out:
        assert r["difficulty"] in ("easy", "medium", "hard"), r
        assert r["text"] and r["hint"], r
    assert len(out) == len(set(r["text"] for r in out)), "dup remains"

    json.dump(out, open("/tmp/draw_merged.json", "w"), ensure_ascii=False)
    print(f"现有 {len(existing)} → 合并后 {len(out)}（新增 {added}，跳过重复 {dup}）")
    print("难度分布:", dict(Counter(r["difficulty"] for r in out)))
    print("类别分布:")
    for h, c in Counter(r["hint"] for r in out).most_common():
        print(f"  {h}: {c}")


if __name__ == "__main__":
    main()
